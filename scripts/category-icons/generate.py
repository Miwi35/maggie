#!/usr/bin/env python3
"""Generate the category icon catalogue (MAG-502).

    task icons:generate            # rewrite the generated files
    task icons:generate -- --check # fail if they are not what the sources give

The catalogue is every « filled » Material icon that both clients can draw: the names of
`@mui/icons-material` (admin, version of admin/package-lock.json) that also exist in
`androidx.compose.material:material-icons-core` + `-extended` (mobile, version of the Compose BOM
in mobile/gradle/libs.versions.toml). `Category.icon` stores the icon's name in kebab case
(`local-gas-station`).

Hand-written input: `french.json`, the French label and search words of the common icons, in the
order the picker lists them. Every other icon gets its English name as label and is found by
that name. Output (standard library only; needs network to fetch the two packages):

  design/category-icons.json                              the catalogue both clients are tested against
  admin/.../categoryIconData.generated.ts                 the same catalogue, for the Vite build
  admin/.../categoryIconShapes.generated.ts               the SVG of each icon (what MUI would import)
  mobile/.../CategoryIconData.kt                          the same catalogue, for the app
  mobile/.../CategoryIconVectors.kt                       name -> Compose ImageVector
"""

import argparse
import base64
import hashlib
import http.client
import io
import json
import re
import sys
import tarfile
import tempfile
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
ADMIN_DIR = ROOT / "admin/src/modules/finance"
MOBILE_DIR = ROOT / "mobile/app/src/main/java/com/maggie/app/ui/screens/finance"
OUTPUTS = {
    "design": ROOT / "design/category-icons.json",
    "admin_data": ADMIN_DIR / "categoryIconData.generated.ts",
    "admin_shapes": ADMIN_DIR / "categoryIconShapes.generated.ts",
    "mobile_data": MOBILE_DIR / "CategoryIconData.kt",
    "mobile_vectors": MOBILE_DIR / "CategoryIconVectors.kt",
}
VARIANT_SUFFIXES = ("Outlined", "Rounded", "Sharp", "TwoTone")
GOOGLE_MAVEN = "https://dl.google.com/android/maven2"
HEADER = "Generated by scripts/category-icons/generate.py (MAG-502) — do not edit; run `task icons:generate`."
# Kotlin methods are capped at 64 KB of bytecode: the tables are cut in chunks.
KOTLIN_CHUNK = 150


CACHE = Path(tempfile.gettempdir()) / "maggie-category-icons"


def fetch(url: str) -> bytes:
    """The body of an https URL, kept in a temp directory: three tries, the downloads are big."""
    cached = CACHE / hashlib.sha1(url.encode()).hexdigest()  # noqa: S324 (a file name, not a secret)
    if cached.exists():
        return cached.read_bytes()
    for attempt in range(3):
        try:
            print(f"fetching {url}", file=sys.stderr)
            with urllib.request.urlopen(url, timeout=300) as response:  # noqa: S310 (fixed https URLs)
                data = response.read()
            CACHE.mkdir(parents=True, exist_ok=True)
            cached.write_bytes(data)
            return data
        except (OSError, http.client.HTTPException):
            if attempt == 2:
                raise
    raise AssertionError("unreachable")


def mui_package() -> tuple[str, dict[str, str]]:
    lock = json.loads((ROOT / "admin/package-lock.json").read_text())
    entry = lock["packages"]["node_modules/@mui/icons-material"]
    version, integrity = entry["version"], entry["integrity"]
    data = fetch(entry["resolved"])
    algorithm, expected = integrity.split("-", 1)
    if base64.b64encode(hashlib.new(algorithm, data).digest()).decode() != expected:
        sys.exit("@mui/icons-material: the downloaded tarball does not match the lockfile's integrity")
    files: dict[str, str] = {}
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        for member in tar.getmembers():
            match = re.fullmatch(r"package/esm/([A-Z][A-Za-z0-9]*)\.js", member.name)
            if match:
                files[match.group(1)] = tar.extractfile(member).read().decode()  # type: ignore[union-attr]
    return version, files


def compose_icons() -> tuple[str, dict[str, bool]]:
    """Name -> True when the icon lives under Icons.AutoMirrored.Filled (it flips in right-to-left)."""
    catalog = (ROOT / "mobile/gradle/libs.versions.toml").read_text()
    bom = re.search(r'^compose-bom = "([^"]+)"', catalog, re.M).group(1)  # type: ignore[union-attr]
    pom = fetch(f"{GOOGLE_MAVEN}/androidx/compose/compose-bom/{bom}/compose-bom-{bom}.pom").decode()
    version = re.search(
        r"<artifactId>material-icons-extended</artifactId>\s*<version>([^<]+)</version>", pom
    ).group(1)  # type: ignore[union-attr]
    icons: dict[str, bool] = {}
    for artifact in ("material-icons-core-android", "material-icons-extended-android"):
        base = f"{GOOGLE_MAVEN}/androidx/compose/material/{artifact}/{version}/{artifact}-{version}"
        aar = fetch(f"{base}.aar")
        sha1 = fetch(f"{base}.aar.sha1").decode().split()[0]
        if hashlib.sha1(aar).hexdigest() != sha1:  # noqa: S324 (Maven's own checksum)
            sys.exit(f"{artifact}: the downloaded aar does not match Maven's checksum")
        with zipfile.ZipFile(io.BytesIO(aar)) as archive, zipfile.ZipFile(io.BytesIO(archive.read("classes.jar"))) as jar:
            for entry in jar.namelist():
                match = re.fullmatch(
                    r"androidx/compose/material/icons/(automirrored/)?filled/([A-Za-z0-9]+)Kt\.class", entry
                )
                if match:
                    icons[match.group(2)] = icons.get(match.group(2), False) or bool(match.group(1))
    return version, icons


def kebab(pascal: str) -> str:
    return re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", "-", pascal).lower()


def shape_of(source: str) -> str | list:
    """The SVG of one MUI icon: a path's `d` when that is all there is, else its elements."""
    elements = []
    for tag, body in re.findall(r'_jsx\("(\w+)", \{(.*?)\}(?:, "\d+")?\)', source, re.S):
        props = dict(re.findall(r'(\w+): "([^"]*)"', body))
        elements.append((tag, props))
    if not elements or len(elements) != len(re.findall(r'_jsx\("', source)):
        sys.exit("an icon has an element the generator does not read")
    if len(elements) == 1 and elements[0][0] == "path" and list(elements[0][1]) == ["d"]:
        return elements[0][1]["d"]
    return [[tag, props] for tag, props in elements]


def english_label(name: str) -> str:
    words = name.replace("-", " ")
    return words[:1].upper() + words[1:]


def build_catalogue(common: set[str]) -> list[dict]:
    french = json.loads((HERE / "french.json").read_text())
    names = [entry[0] for entry in french]
    if len(set(names)) != len(names):
        sys.exit(f"french.json lists twice: {sorted({n for n in names if names.count(n) > 1})}")
    unknown = [n for n in names if n not in common]
    if unknown:
        sys.exit(f"french.json names icons that do not exist on both sides: {unknown}")
    catalogue = [{"name": n, "label": label, "keywords": keywords} for n, label, keywords in french]
    catalogue += [
        {"name": n, "label": english_label(n), "keywords": []} for n in sorted(common - set(names))
    ]
    labels: dict[str, str] = {}
    clashes = []
    for entry in catalogue:
        key = entry["label"].lower()
        if key in labels:
            clashes.append(f"« {entry['label']} »: {labels[key]} and {entry['name']}")
        labels[key] = entry["name"]
    if clashes:
        sys.exit("icons sharing a label (a tile is found by its label): " + "; ".join(clashes))
    for first in ("home", "shopping-cart", "savings"):
        assert first in names, first
    return catalogue


def ts_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def kt_string(text: str) -> str:
    return json.dumps(text, ensure_ascii=False).replace("$", "\\$")


def render_design(catalogue: list[dict], mui: str, compose: str) -> str:
    lines = [
        "{",
        f'  "generatedBy": {json.dumps("scripts/category-icons/generate.py")},',
        f'  "sources": {json.dumps({"@mui/icons-material": mui, "material-icons-extended": compose})},',
        '  "icons": [',
    ]
    rows = [f"    {json.dumps(entry, ensure_ascii=False)}" for entry in catalogue]
    lines.append(",\n".join(rows))
    lines += ["  ]", "}", ""]
    return "\n".join(lines)


def render_admin_data(catalogue: list[dict]) -> str:
    rows = [
        f"  [{ts_string(e['name'])}, {ts_string(e['label'])}, [{', '.join(ts_string(k) for k in e['keywords'])}]],"
        for e in catalogue
    ]
    return "\n".join(
        [
            f"// {HEADER}",
            "/** Name (the value of `Category.icon`), French label, French search words. */",
            "export const CATEGORY_ICON_DATA: ReadonlyArray<readonly [string, string, readonly string[]]> = [",
            *rows,
            "]",
            "",
        ]
    )


def render_admin_shapes(shapes: dict[str, str | list]) -> str:
    rows = []
    for name, shape in shapes.items():
        if isinstance(shape, str):
            rows.append(f"  {ts_string(name)}: {ts_string(shape)},")
        else:
            elements = ", ".join(
                f"[{ts_string(tag)}, {json.dumps(props, ensure_ascii=False)}]" for tag, props in shape
            )
            rows.append(f"  {ts_string(name)}: [{elements}],")
    return "\n".join(
        [
            f"// {HEADER}",
            "export type IconElement = readonly [tag: string, props: Readonly<Record<string, string>>]",
            "/** A path's `d`, or the elements of an icon that is more than one plain path. */",
            "export type IconShape = string | readonly IconElement[]",
            "",
            "export const CATEGORY_ICON_SHAPES: Readonly<Record<string, IconShape>> = {",
            *rows,
            "}",
            "",
        ]
    )


def chunks(items: list, size: int) -> list[list]:
    return [items[i : i + size] for i in range(0, len(items), size)]


def render_mobile_data(catalogue: list[dict]) -> str:
    parts = chunks(catalogue, KOTLIN_CHUNK)
    out = [
        f"// {HEADER}",
        "package com.maggie.app.ui.screens.finance",
        "",
        "/** Name (the value of `Category.icon`), French label, French search words. */",
        "internal class CategoryIconRow(val name: String, val label: String, val keywords: List<String>)",
        "",
        "internal object CategoryIconData {",
        "    val rows: List<CategoryIconRow> = " + " + ".join(f"part{i}()" for i in range(len(parts))),
        "",
        "    private fun e(name: String, label: String, vararg keywords: String) =",
        "        CategoryIconRow(name, label, keywords.toList())",
    ]
    for i, part in enumerate(parts):
        out += ["", f"    private fun part{i}(): List<CategoryIconRow> = listOf("]
        for e in part:
            args = ", ".join(kt_string(s) for s in [e["name"], e["label"], *e["keywords"]])
            out.append(f"        e({args}),")
        out.append("    )")
    out += ["}", ""]
    return "\n".join(out)


def render_vectors(entries: list[tuple[str, str, bool]]) -> str:
    imports = sorted(
        {
            f"import androidx.compose.material.icons.{'automirrored.' if mirrored else ''}filled.{pascal}"
            for _, pascal, mirrored in entries
        }
    )
    parts = chunks(entries, KOTLIN_CHUNK)
    out = [
        f"// {HEADER}",
        "package com.maggie.app.ui.screens.finance",
        "",
        "import androidx.compose.material.icons.Icons",
        *imports,
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "",
        "/** The Compose icon behind each name of the catalogue; null for a name we do not draw. */",
        "internal object CategoryIconVectors {",
        "    fun find(name: String): ImageVector? =",
        "        " + "\n            ?: ".join(f"part{i}(name)" for i in range(len(parts))),
    ]
    for i, part in enumerate(parts):
        out += ["", f"    private fun part{i}(name: String): ImageVector? = when (name) {{"]
        for name, pascal, mirrored in part:
            holder = "Icons.AutoMirrored.Filled" if mirrored else "Icons.Filled"
            out.append(f"        {kt_string(name)} -> {holder}.{pascal}")
        out += ["        else -> null", "    }"]
    out += ["}", ""]
    return "\n".join(out)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="write nothing; fail if a generated file differs")
    args = parser.parse_args()

    mui_version, mui_files = mui_package()
    compose_version, compose = compose_icons()

    mui_filled = {
        name
        for name in mui_files
        if not any(name.endswith(s) and name[: -len(s)] in mui_files for s in VARIANT_SUFFIXES)
    }
    pascal_of = {kebab(p): p for p in sorted(mui_filled & compose.keys())}
    if len(pascal_of) != len(mui_filled & compose.keys()):
        sys.exit("two icons have the same kebab-case name")
    catalogue = build_catalogue(set(pascal_of))
    print(f"{len(catalogue)} icons ({len(mui_filled)} in MUI, {len(compose)} in Compose)", file=sys.stderr)

    shapes = {entry["name"]: shape_of(mui_files[pascal_of[entry["name"]]]) for entry in catalogue}
    vectors = [(e["name"], pascal_of[e["name"]], compose[pascal_of[e["name"]]]) for e in catalogue]

    rendered = {
        "design": render_design(catalogue, mui_version, compose_version),
        "admin_data": render_admin_data(catalogue),
        "admin_shapes": render_admin_shapes(shapes),
        "mobile_data": render_mobile_data(catalogue),
        "mobile_vectors": render_vectors(vectors),
    }
    stale = [key for key, text in rendered.items() if not OUTPUTS[key].exists() or OUTPUTS[key].read_text() != text]
    if args.check:
        if stale:
            sys.exit("out of date: " + ", ".join(str(OUTPUTS[k].relative_to(ROOT)) for k in stale))
        print("up to date", file=sys.stderr)
        return
    for key in stale:
        OUTPUTS[key].write_text(rendered[key])
        print(f"wrote {OUTPUTS[key].relative_to(ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
