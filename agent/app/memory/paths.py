"""Where a file of the memory folder lives, and what may never leave its owner's prefix.

    <user>/Mémoire/
      LISEZMOI.md, AGENTS.md, sommaire.md, journal.md   generated by Maggie
      Conversations/AAAA/MM/AAAA-MM-JJ HHhMM — <sujet>.md
      Conflits/…                                         Maggie's versions set aside for the owner's
      <folders Maggie chooses>/…

`<user>` is the user's ULID (the JWT `sub`): the one shape that cannot hold a separator, a dot or a
space. The bucket key of a file is `<user>/Mémoire/<relative path>`, its local path
`<root>/<user>/Mémoire/<relative path>`. A relative path is validated before it is used for anything,
and the local one is resolved and checked once more against the folder it must stay in.
"""

import re
import unicodedata
from collections.abc import Iterable
from datetime import datetime
from pathlib import Path

from app.memory.ulid import is_ulid

MEMORY_DIR = "Mémoire"
CONVERSATIONS_DIR = "Conversations"
CONFLICTS_DIR = "Conflits"
EXTENSION = ".md"

README = "LISEZMOI.md"
AGENTS = "AGENTS.md"
SUMMARY = "sommaire.md"
JOURNAL = "journal.md"
GENERATED_FILES = (README, AGENTS, SUMMARY, JOURNAL)

# Taken at the root, whatever the case: a fiche cannot be named like a generated file or like the
# folders Maggie keeps for herself.
RESERVED_ROOT = frozenset(
    name.casefold()
    for name in (
        *(file.removesuffix(EXTENSION) for file in GENERATED_FILES),
        CONVERSATIONS_DIR,
        CONFLICTS_DIR,
    )
)

# A file name is bounded in bytes, not characters: ext4 stops at 255, an accent costs two.
MAX_STEM_BYTES = 180
MAX_SEGMENT_BYTES = 240
MAX_RELATIVE_BYTES = 600
MAX_DEPTH = 6
UNTITLED = "Sans titre"

_CONTROL = re.compile(r"[\x00-\x1f\x7f-\x9f]")
_SPACES = re.compile(r"\s+")
# What a title loses to become a file name: what a path cannot carry. Accents stay.
_NOT_IN_A_NAME = re.compile(r"[/\\:]")


class UnsafePath(ValueError):
    """A user id or a path that would step outside its prefix, or onto a name Maggie keeps."""


def check_user_id(user_id: str) -> str:
    if not is_ulid(user_id):
        raise UnsafePath(f"{user_id!r} is not a user id the bucket can use as a prefix")
    return user_id


def bucket_prefix(user_id: str) -> str:
    return f"{check_user_id(user_id)}/{MEMORY_DIR}/"


def bucket_key(user_id: str, rel: str) -> str:
    return bucket_prefix(user_id) + clean_relative(rel)


def relative_from_key(user_id: str, key: str) -> str | None:
    """The relative path of a bucket key of this user's folder, None for anything else (another user, other files)."""
    prefix = bucket_prefix(user_id)
    if not key.startswith(prefix):
        return None
    try:
        return clean_relative(key[len(prefix) :])
    except UnsafePath:
        return None


def user_of_key(key: str) -> str | None:
    """The user whose Mémoire folder holds this key, None for everything else (skills, strays)."""
    first, _, rest = key.partition("/")
    if is_ulid(first) and rest.startswith(f"{MEMORY_DIR}/"):
        return first
    return None


def clean_relative(rel: str) -> str:
    """`rel` normalised and proven safe, or `UnsafePath`: no way out of the folder, no hidden or empty segment."""
    if not isinstance(rel, str) or not rel:
        raise UnsafePath("empty path")
    rel = unicodedata.normalize("NFC", rel)
    if rel.startswith("/") or "\\" in rel or _CONTROL.search(rel):
        raise UnsafePath(f"{rel!r} is not a relative path of the folder")
    segments = rel.split("/")
    if len(segments) > MAX_DEPTH:
        raise UnsafePath(f"{rel!r} is nested too deep")
    for segment in segments:
        if segment in ("", ".", "..") or segment.startswith(".") or segment != segment.strip():
            raise UnsafePath(f"{rel!r} holds a segment that cannot be used")
        if len(segment.encode("utf-8")) > MAX_SEGMENT_BYTES:
            raise UnsafePath(f"{rel!r} holds a name that is too long")
    if len(rel.encode("utf-8")) > MAX_RELATIVE_BYTES:
        raise UnsafePath(f"{rel!r} is too long")
    return rel


def local_path(root: Path, user_id: str, rel: str) -> Path:
    """Where the file sits on disk, proven to be inside this user's folder."""
    folder = (root / check_user_id(user_id) / MEMORY_DIR).resolve()
    target = (folder / clean_relative(rel)).resolve()
    if not target.is_relative_to(folder) or target == folder:
        raise UnsafePath(f"{rel!r} leaves the folder of {user_id}")
    return target


def _bounded(text: str, limit: int) -> str:
    encoded = text.encode("utf-8")
    if len(encoded) <= limit:
        return text
    return encoded[:limit].decode("utf-8", errors="ignore")


def filename_for(title: str) -> str:
    """The file name (without extension) of a title: only what a path cannot carry goes, accents stay.

    `/`, `\\`, `:` and control characters are dropped, spaces collapse, a leading dot goes so that
    nothing is hidden, and the length is bounded in bytes.
    """
    text = unicodedata.normalize("NFC", title)
    text = _CONTROL.sub("", _NOT_IN_A_NAME.sub("", text))
    text = _SPACES.sub(" ", text).strip().lstrip(".").strip()
    text = _bounded(text, MAX_STEM_BYTES).rstrip(" .")
    return text or UNTITLED


def is_reserved_name(directory: str, stem: str) -> bool:
    return directory == "" and stem.casefold() in RESERVED_ROOT


def unique_relative(directory: str, stem: str, taken: Iterable[str]) -> str:
    """`<directory>/<stem>.md`, or `<stem>-2.md`, `-3`… when the name is taken (case apart) or reserved."""
    used = {t.casefold() for t in taken}
    prefix = f"{directory}/" if directory else ""
    attempt = 1
    while True:
        candidate_stem = stem if attempt == 1 else f"{stem}-{attempt}"
        candidate = f"{prefix}{candidate_stem}{EXTENSION}"
        if candidate.casefold() not in used and not is_reserved_name(directory, candidate_stem):
            return clean_relative(candidate)
        attempt += 1


def fiche_relative(folders: Iterable[str], title: str, taken: Iterable[str]) -> str:
    """Where a fiche goes: shallow folders Maggie chose, the title as the name."""
    parts = [filename_for(folder) for folder in folders if folder.strip()]
    if parts and parts[0].casefold() in RESERVED_ROOT:
        raise UnsafePath(f"{parts[0]!r} is a name Maggie keeps for herself")
    return unique_relative("/".join(parts), filename_for(title), taken)


def conversation_relative(when: datetime, subject: str, taken: Iterable[str]) -> str:
    """`Conversations/2026/10/2026-10-04 18h14 — Cadeau fête des mères.md`."""
    stamp = when.strftime("%Y-%m-%d %Hh%M")
    stem = _bounded(f"{stamp} — {filename_for(subject)}", MAX_STEM_BYTES).rstrip(" .")
    return unique_relative(f"{CONVERSATIONS_DIR}/{when:%Y}/{when:%m}", stem, taken)


def conflict_relative(rel: str, when: datetime, taken: Iterable[str]) -> str:
    stem = filename_for(f"{Path(rel).stem} — version de Maggie {when:%Y-%m-%d %Hh%M}")
    return unique_relative(CONFLICTS_DIR, stem, taken)


def is_generated(rel: str) -> bool:
    return rel in GENERATED_FILES


def is_syncable(rel: str) -> bool:
    """What travels between the bucket and the local copy: Markdown files, nothing hidden."""
    return rel.endswith(EXTENSION) and len(rel) > len(EXTENSION)


def is_indexable(rel: str) -> bool:
    """What the index reads: the fiches and the conversations, not the generated files nor the set-aside versions."""
    return is_syncable(rel) and not is_generated(rel) and rel.split("/", 1)[0] != CONFLICTS_DIR


def kind_of(rel: str) -> str:
    return "conversation" if rel.split("/", 1)[0] == CONVERSATIONS_DIR else "fiche"


def check_writable(rel: str, *, generated: bool = False, conversation: bool = False) -> str:
    """Refuse a write onto what is not Maggie's to write there: generated files, Conversations/ and Conflits/."""
    rel = clean_relative(rel)
    if not is_syncable(rel):
        raise UnsafePath(f"{rel!r} is not a Markdown file")
    if is_generated(rel):
        if not generated:
            raise UnsafePath(f"{rel!r} is generated, not written by hand")
        return rel
    top = rel.split("/", 1)[0].casefold()
    if "/" not in rel and rel.removesuffix(EXTENSION).casefold() in RESERVED_ROOT:
        raise UnsafePath(f"{rel!r} is a name Maggie keeps for herself")
    if top == CONFLICTS_DIR.casefold():
        if not generated:
            raise UnsafePath("Conflits/ is written by the synchronisation only")
    elif top == CONVERSATIONS_DIR.casefold() and not conversation:
        raise UnsafePath("Conversations/ holds conversations only")
    return rel
